-- 018: store the structured AI "meeting minutes" for human-answered calls.
--
-- WHY: the human line (Twilio direct line) had two disconnected halves —
--   1. the production recording callback wrote a *triage* summary
--      (intent / tendency / follow-up priority), and
--   2. the rich "meeting minutes" payload (key facts, action items,
--      recommendation) only existed on a standalone demo page fed by
--      hard-coded sample transcripts.
-- The thing the demo was actually for — "what did Alex write down after this
-- call?" — was never reachable in production.
--
-- human_minutes holds that payload verbatim as JSONB so the detail page can
-- render action items and key facts without re-running the LLM. The same
-- values are ALSO mapped onto the normal work_orders columns so the main
-- dashboard keeps working for human calls exactly like AI calls.
--
-- human_minutes_source records how it was produced:
--   'llm'  — generated by the model
--   'none' — generation failed or there was no transcript
-- NULL    — never attempted (AI calls, or a human call before this column)

alter table work_orders
  add column if not exists human_minutes jsonb;

alter table work_orders
  add column if not exists human_minutes_source text;

comment on column work_orders.human_minutes is
  'Structured AI meeting minutes for human-answered calls: summary, intent, key_facts, action_items, topics_mentioned, customer_tendency, follow_up_priority, follow_up_recommendation';

comment on column work_orders.human_minutes_source is
  'How human_minutes was produced: llm | none. NULL = never attempted.';
